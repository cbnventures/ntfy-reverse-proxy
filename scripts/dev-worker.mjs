import { spawn } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import {
  dirname, join, relative, resolve, sep,
} from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Dev Worker - Toolkit.
 *
 * Holds the toolkit namespace once the guarded dynamic import resolves so
 * the batteries below can be read from a single typed source.
 *
 * @since 2.0.0
 */
let toolkit = /** @type {typeof import('@cbnventures/nova/toolkit') | undefined} */ (undefined);

try {
  toolkit = await import('@cbnventures/nova/toolkit');
} catch {
  process.stderr.write('dev-worker.mjs: requires @cbnventures/nova to be built. Run "npm run build" first.\n');

  process.exit(1);
}

/**
 * Dev Worker - Bootstrap.
 *
 * Holds the toolkit Bootstrap helper once the guarded dynamic import
 * resolves, giving path helpers such as the XDG config directory.
 *
 * @since 2.0.0
 */
const bootstrap = toolkit['Bootstrap'];

/**
 * Dev Worker - Logger.
 *
 * Holds the toolkit Logger once the guarded dynamic import resolves so
 * status and error output share the project logging format.
 *
 * @since 2.0.0
 */
const logger = toolkit['Logger'];

/**
 * Dev Worker - Project Root.
 *
 * Absolute path to the repository root, resolved one level up from this
 * script directory, used to locate config and wrangler files.
 *
 * @since 2.0.0
 */
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Dev Worker - App Name.
 *
 * Application slug passed to the toolkit config-directory helper so XDG
 * lookups resolve under this project's namespace.
 *
 * @since 2.0.0
 */
const APP_NAME = 'ntfy-reverse-proxy';

/**
 * Dev Worker - Resolve Config JSON.
 *
 * Searches for config.json in the project root, then the XDG
 * config directory, and returns the first match.
 *
 * @returns {string | undefined}
 *
 * @since 2.0.0
 */
function resolveConfigJson() {
  const localPath = join(projectRoot, 'config.json');
  const xdgPath = join(bootstrap.getConfigDir(APP_NAME), 'config.json');

  if (existsSync(localPath) === true) {
    return localPath;
  }

  if (existsSync(xdgPath) === true) {
    return xdgPath;
  }

  return undefined;
}

/**
 * Dev Worker - Get Compatibility Date.
 *
 * Returns today's date capped at the newest date the local Workers runtime supports,
 * loading workerd the same way Wrangler does (through its own miniflare).
 *
 * @returns {string}
 *
 * @since 0.0.0
 */
function getCompatibilityDate() {
  const today = new Date().toISOString().slice(0, 10);

  try {
    const wranglerEntry = createRequire(import.meta.url).resolve('wrangler');
    const miniflareEntry = createRequire(wranglerEntry).resolve('miniflare');
    const runtimeDate = createRequire(miniflareEntry)('workerd')['compatibilityDate'];

    if (typeof runtimeDate === 'string' && runtimeDate < today) {
      return runtimeDate;
    }
  } catch {
    // Keep today's date when the local runtime cannot be located.
  }

  return today;
}

/**
 * Dev Worker - Generate Wrangler Toml.
 *
 * Reads config.json and writes a wrangler.toml plus the Worker entry and config file in
 * .wrangler/ntfy-reverse-proxy, the same layout the CLI uses, with the entry on the source.
 *
 * @param {string} configJsonPath - Config json path.
 * @param {string} outputPath     - Output path.
 *
 * @returns {void}
 *
 * @since 2.0.0
 */
function generateWranglerToml(configJsonPath, outputPath) {
  const config = JSON.parse(readFileSync(configJsonPath, 'utf-8'));
  const settings = config['settings'];
  const contexts = /** @type {{ id: string, type: string }[]} */ (config['contexts']);
  const compatibilityDate = getCompatibilityDate();
  const bundleDir = join(dirname(outputPath), '.wrangler', 'ntfy-reverse-proxy');
  const sourceEntryPath = join(projectRoot, 'packages', 'ntfy-reverse-proxy', 'src', 'worker', 'index.ts');

  mkdirSync(bundleDir, { recursive: true });

  // Wrangler bundles from real paths, so measure the import from the real folder in case of symlinks.
  const sourceImportPath = relative(realpathSync(bundleDir), realpathSync(sourceEntryPath)).split(sep).join('/');

  const entryLines = [
    '// Generated by scripts/dev-worker.mjs.',
    `import { createWorker } from ${JSON.stringify(sourceImportPath)};`,
    '',
    'import config from "./config.json";',
    '',
    'export default createWorker(config);',
    '',
    `export { DeliveryOutbox } from ${JSON.stringify(sourceImportPath)};`,
  ];

  const httpContexts = contexts.filter((context) => context['type'] === 'http');
  const emailContexts = contexts.filter((context) => context['type'] === 'email');

  const routeLines = httpContexts.map((context) => {
    return `  { pattern = "${context['id']}.${settings['base_domain']}", custom_domain = true },`;
  });

  const lines = [
    `name = "${settings['worker_name']}"`,
    'main = ".wrangler/ntfy-reverse-proxy/worker.js"',
    `compatibility_date = "${compatibilityDate}"`,
    '',
    '################',
    '#### Routes ####',
    '################',
    'routes = [',
    ...routeLines,
    ']',
  ];

  if (emailContexts['length'] > 0) {
    lines.push('');
    lines.push('#######################');
    lines.push('#### Email Routing ####');
    lines.push('#######################');
    lines.push('# Configure these email addresses in Cloudflare Email Routing:');

    for (const context of emailContexts) {
      lines.push(`# - ${context['id']}@${settings['base_domain']} -> Worker`);
    }
  }

  // The delivery outbox Durable Object needs the same binding and migration the CLI writes.
  lines.push('');
  lines.push('#########################');
  lines.push('#### Durable Objects ####');
  lines.push('#########################');
  lines.push('[[durable_objects.bindings]]');
  lines.push('name = "DELIVERY_OUTBOX"');
  lines.push('class_name = "DeliveryOutbox"');
  lines.push('');
  lines.push('[[migrations]]');
  lines.push('tag = "v1"');
  lines.push('new_sqlite_classes = ["DeliveryOutbox"]');

  writeFileSync(join(bundleDir, 'config.json'), `${JSON.stringify(config, null, 2)}\n`);
  writeFileSync(join(bundleDir, 'worker.js'), `${entryLines.join('\n')}\n`);
  writeFileSync(outputPath, `${lines.join('\n')}\n`);

  return;
}

/**
 * Dev Worker - Resolve Wrangler Config.
 *
 * Finds the active config.json and regenerates wrangler.toml plus its bundled
 * Worker files on every run so local configuration edits cannot go stale.
 *
 * @returns {string}
 *
 * @since 0.0.0
 */
function resolveWranglerConfig() {
  const configJsonPath = resolveConfigJson();

  if (configJsonPath === undefined) {
    logger.error('No config.json found. Copy config.sample.json to config.json and configure it.');

    process.exit(1);
  }

  const outputPath = join(dirname(configJsonPath), 'wrangler.toml');

  logger.info(`Regenerating wrangler.toml and the local Worker bundle from ${configJsonPath}...`);

  generateWranglerToml(configJsonPath, outputPath);

  logger.info(`Generated wrangler.toml: ${outputPath}`);

  return outputPath;
}

/**
 * Dev Worker - Config Path.
 *
 * Resolved wrangler.toml path chosen or generated for this run, passed
 * to wrangler dev as the active configuration file.
 *
 * @since 2.0.0
 */
const configPath = resolveWranglerConfig();

/**
 * Dev Worker - Wrangler.
 *
 * Child process running wrangler dev in local mode; its exit code is
 * propagated to the parent shell when the process closes.
 *
 * @since 2.0.0
 */
const wrangler = spawn('npx', [
  'wrangler',
  'dev',
  '--config',
  configPath,
  '--local-upstream',
  'localhost',
  '--inspector-port=0',
], {
  stdio: 'inherit',
});

wrangler.on('close', (code) => {
  return process.exit(code ?? 1);
});
